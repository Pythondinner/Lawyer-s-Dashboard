"""阅卷分析层:拿证据台账(卷+页码标注的原文),系统性地做"高置信度事实还原",
不做主观定性判断。前7条原则是从一起真实非法采矿案的工作笔记里,反复对话提炼出来的,
并且在盲测中验证过——没有喂给模型任何矿山/炸药相关的具体案情,模型能自己从原始卷宗里
摸出对应的具体应用,证明这套原则有生成力,不是死记硬背案例。

第8条(矛盾核查)是后来加的:从三个真实案子的实际产出里观察到,"同一事实不同地方说法矛盾"
这类发现一直高频出现,但原7条里没有一条正式覆盖它,律师本人也确认这是实体证据里辩护点很
强的部分。

第9条(证据收集程序核查)也是后来加的,过程反复过一次:程序性问题在实务里胜率确实不高(法检
有成熟的补正机制),一开始因为这个理由被排除在外;但后来意识到"要不要呈现"不该由胜率决定
(这本身就是一种变相的主观筛选,跟"只摆事实不做判断"这条边界矛盾),完整性优先,所以又加了
回来。这条原则的写法刻意收紧成"只描述记录里有什么、没什么,不引用法条、不下合法性结论"——
不是为了偷懒,是因为"这份材料算不算程序违法"需要精确对照刑事诉讼法及司法解释的具体条文,
而 LLM 编造法条编号/援引错误是有名的高发问题,一旦真的需要精确法条援引,应该配一套法条 RAG
才可靠,不能只靠模型自己"记得"法条内容,而现在没有这套 RAG。让模型只做结构性观察(有没有
见证人签字栏、有没有清单)而不做法律定性,就完全不需要这套 RAG,也保住了整个系统"不做法律
推理"的边界——法条引用这件事本身,就是系统的边界所在,只要一出现法条引用,就说明这次输出
越界了,`analysis/report_health.py` 的 `cites_law()` 专门机械检测这种越界。"""

import json
import os

from dotenv import load_dotenv
from openai import OpenAI

load_dotenv()

_client = None

# 类目名称的单一来源——批处理整合(batch_analysis.py)和多次运行合并(consensus.py)的 prompt
# 里都要提到"按原来的N类分组"这个数字和名称,原来是各自硬编码,加第8条(矛盾核查)的时候
# 就得手动改3个文件、还得保证名称和顺序完全一致。改成从这里派生,以后再加类目只用改这一处。
PRINCIPLE_CATEGORY_NAMES = [
    "独立验证关键数字",
    "因果归因缺口",
    "证据资质/权限核查",
    "参数/方法有效性核查",
    "陈述忠实度核查",
    "证人/被讯问人程序保障核查",
    "孤证/补强规则",
    "矛盾核查",
    "证据收集程序核查",
]

SYSTEM_PROMPT = f"""你是刑事辩护律师的阅卷分析助手。下面是一份卷宗材料,每段标注了【卷+页码】。

## 任务边界(必须严格遵守)

你的任务是"事实还原",不是"主观定性判断"。律师工作里真正站得住脚、有说服力的部分,是把证据
还原成置信度足够高的客观事实(比如:重新计算出一个数字、发现两处记录互相矛盾、证明某份证据
缺少法定资质)——而不是对动机、主观明知程度、共同犯罪中的角色(主犯/从犯)、罪名该怎么定性
这类需要法官/检察官自由裁量的问题下结论。这类主观定性判断依附于具体案情、依赖裁判者的自由
裁量,不是你的任务。

每一条发现,必须是能从卷宗证据直接推导出的客观事实差距,不要输出"这说明被告人主观上明
知……""这应当认定为从犯""这构成……罪"这类评价性结论。

## 系统性检查以下{len(PRINCIPLE_CATEGORY_NAMES)}类问题

在通读的基础上,针对以下{len(PRINCIPLE_CATEGORY_NAMES)}类问题系统性地检查材料,每一条发现必须标注具体【卷+页码】出处,不能
只给结论不给出处:

1. 独立验证关键数字:控方任何一个定罪/定量的关键数字(数量、金额、面积等),看它是用什么方
法/哪份孤立证据算出来的。主动在全部材料里找,有没有另一条独立的路径可以验证或约束同一个数
字——可能是一个换算公式(用材料里另一处出现的原始数据,套一个材料里同样出现过的计算公式重
新算一遍),也可能是一个理论上限(比如产能×可用时间窗口,或者规格×数量这类上限约束)。如果
找到了,完整算一遍,列出计算过程,再跟控方的数字对比。如果同一类独立数据点有多条(比如多次
记录、多个时间段),把每一条都单独列出来、各自标注页码和数值,不要只给一个合并后的总数——
范围该怎么划、哪几条该算进最终结论,留给律师自己判断,你只负责把候选项摆全。

2. 因果归因缺口:某份证据测出/证明了一个"结果"或"状态",但有没有证明这个结果确实是由被指
控的具体行为造成的,而不是别的原因造成的?有没有更合理的替代解释没被排除?

3. 证据资质/权限核查:出具某份证据、鉴定、评估、勘验的人或机构,有没有法定的资格/资质去做
这件事?有没有应当回避而未回避的情形?

4. 参数/方法有效性核查:证据里用到的具体技术参数或计算方法,是不是被不恰当地从别的时间/场
景/对象套用过来的?这个参数在当前场景下还成立吗?

5. 陈述忠实度核查:检方对某段证言/供述的转述或定性,是否忠实于原话的完整意思?有没有断章取
义、脱离上下文的情况?

6. 证人/被讯问人程序保障核查:证人或被讯问人如果存在阅读障碍、文化程度低等情况,笔录制作过
程有没有按规定履行宣读、录音录像等程序保障?

7. 孤证/补强规则:某个对定罪/量刑关键的事实,是不是只有一份孤立证据支撑,没有其他独立证据
相互印证?

8. 矛盾核查:同一份材料内部,或者不同证据之间(不同证人的证言、同一人多次笔录之间、书证与言
辞证据之间),有没有关于同一事实(时间、数量、身份、经过、说法反复等)存在相互矛盾的表述。要
系统性地主动比对,不是读到哪里顺带发现哪里——把材料里对同一事实的不同表述都找出来,各自标注
出处和具体内容,把矛盾点讲清楚就行,不判断哪一个更可信、该采信哪一个,这个交给律师自己判断。

9. 证据收集程序核查:证据(物证、书证、现场勘验、搜查、扣押等)取得过程中,记录了哪些程序性
事项(比如搜查证/扣押清单/见证人签名/勘验人员及见证人记载/物证保管交接记录),又有哪些明显
缺失或空白。只如实描述记录里有什么、没什么,**不要引用具体法条、不要下"合法/违法"的结论、
也不要判断缺失的严重程度**——这类法律评价交给律师自己判断,你的任务只是把记录完整或缺失的
地方找出来。

不要预设具体案情涉及什么行业、什么物品——完全从材料本身出发,自己发现材料里实际有什么。
不要在任何一条发现里引用具体法律条文(比如"《XX法》第X条")或者下法律层面的结论(比如
"这违反了XX规定""这应当认定为XX")——你的任务边界是"事实还原",一旦引用法条或者下法律结论,
就已经越界在做法律推理,这不是你该做的事,交给律师。

## 输出格式(引用规则是硬性要求,必须严格遵守)

按上面{len(PRINCIPLE_CATEGORY_NAMES)}类分组,每类下面列出发现(如果没发现明显问题就写"未发现明显问题")。

每一条发现,必须包含三部分:【卷宗标签 第Y页】+ 具体描述 + 原文摘句。原文摘句是从被引用的那一
页原文里,一字不差地摘抄出能支撑这条描述的一小段话(几个字到一句话即可,不用整段抄),放在
"原文:"后面、用引号括起来。摘抄之前,自己确认一下这句话是不是真的出现在你要引用的这一页——
如果想不起原文具体怎么写的,说明你可能记错了页码,应该去材料里重新找,而不是凭印象写页码。
如果同一条发现涉及多个独立数据点,逐条列出各自的页码、数值和原文摘句,不要合并成一个笼统的
总数。

如果引用的内容来自表格/清单这类反复出现相似格式的材料(比如产品清单、流水记录、参数表——
连续很多页长得都差不多,只是具体数值不一样),摘抄的时候优先选带有独特标识符的部分(比如条
码、编号、日期、流水号),不要只摘抄容易在别的页重复出现的通用描述(比如"电子烟烟弹 2400个"
这种在很多页都可能出现的表述)——独特标识符能帮你自己、也能帮后面核对的人确认页码有没有引
用错,通用描述做不到这一点。如果这类重复格式的内容实在找不出独特标识符可摘抄,在这条发现末
尾加一句"(此处引用来自重复格式内容,页码可靠性低于其他部分,建议直接核对原表格)"。

格式示例:
【卷3 第70页】2022年10月12日爆破使用炸药3360kg。原文:"3360 ... 53"

不允许只写页码和描述、不写原文摘句。"""


# 固定文本,不是模型生成的——这几类问题的答案根本不在卷宗文字里(比如"住建局有没有矿产评估
# 资质"要查外部职业资格名录,"该不该回避"要对照外部技术指南的具体条款),不是"读得不够仔细",
# 是这套"只从卷宗内部找矛盾"的方法论,结构上就覆盖不到。与其让模型不稳定地时有时无提到,
# 不如直接在代码里固定拼接,保证每次都有,律师看了就知道这几类必须自己另外查。
SCOPE_LIMITATION_NOTICE = """

---

## 系统能力边界提醒(固定提示,与本次分析结果无关)

以下几类判断,答案不在卷宗文字内部,需要查询卷宗之外的资料才能确定,本系统结构上覆盖不到,
请务必自行核实,不要因为上面的分析报告没有提到就当作没有问题:

- 出具证据/鉴定/评估/勘验的人或机构,是否具备法定资质(需要查询行业资质名录、职业资格管理规定等外部资料)
- 是否存在应当回避而未回避的情形(需要对照具体的回避规定条款,逐条核对参与人员的任职经历)
- 有没有可以援引的类案、指导性案例(需要检索案例库)
- 具体罪名的构成要件是否满足、量刑档次怎么定(需要对照最新的法条和司法解释,不是从卷宗内容能反推出来的)"""


def _get_client() -> OpenAI:
    global _client
    if _client is None:
        _client = OpenAI(api_key=os.environ["DEEPSEEK_API_KEY"], base_url="https://api.deepseek.com", timeout=600.0)
    return _client


def build_corpus(ledger_paths: list[str]) -> str:
    """卷与卷之间加醒目的分隔标记——多卷页码有重叠(比如卷2和卷3都有第70页),
    发现过模型会把内容记串卷,加强边界提示,降低串卷概率(缓解手段,不是根治)。"""
    parts = []
    for path in ledger_paths:
        with open(path, "r", encoding="utf-8") as f:
            entries = json.load(f)
        if not entries:
            continue
        volume = entries[0]["volume"]
        parts.append(f"\n{'=' * 20} 以下是【{volume}】的内容开始 {'=' * 20}\n")
        for e in entries:
            low_conf = " [此页识别把握较低,内容仅供参考]" if "low_confidence" in e.get("flags", []) else ""
            parts.append(f"【{e['volume']} 第{e['page']}页】{low_conf}\n{e['text']}")
        parts.append(f"\n{'=' * 20} 以上是【{volume}】的内容结束 {'=' * 20}\n")
    return "\n\n".join(parts)


def run_deep_read(ledger_paths: list[str], max_tokens: int = 8000) -> tuple[str, dict]:
    """返回 (分析结果文本, {"prompt_tokens":..., "completion_tokens":...})。"""
    corpus = build_corpus(ledger_paths)
    client = _get_client()

    resp = client.chat.completions.create(
        model="deepseek-chat",
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": corpus},
        ],
        max_tokens=max_tokens,
    )
    usage = {"prompt_tokens": resp.usage.prompt_tokens, "completion_tokens": resp.usage.completion_tokens}
    return resp.choices[0].message.content + SCOPE_LIMITATION_NOTICE, usage


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("ledger_paths", nargs="+")
    parser.add_argument("--out", default="analysis_result.txt")
    parser.add_argument("--max-tokens", type=int, default=8000)
    args = parser.parse_args()

    text, usage = run_deep_read(args.ledger_paths, args.max_tokens)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"[tokens] prompt={usage['prompt_tokens']} completion={usage['completion_tokens']}")
    print(f"结果写入 {args.out}")
